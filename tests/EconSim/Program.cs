// EconSim: the market Ingvar will run, played off-game before anyone plays it.
//
//   dotnet run --project tests\EconSim\EconSim.csproj -c Release                     # to stdout
//   dotnet run --project tests\EconSim\EconSim.csproj -c Release -- --out docs\ECONOMY-SIM.md
//
// Deterministic: one seed, no wall clock, no System.Random, no dictionary order in the
// output. Two runs produce the same bytes. Exit code 1 if an assertion in scenario 7 or 8
// failed, so the script that regenerates the report is also a test.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using RavenIron.ValkyriesCargo.Core;

namespace ValkyriesCargo.EconSim
{
    public static class Program
    {
        public const int MasterSeed = 20260906;

        public static int Main(string[] args)
        {
            string outPath = null;
            long seed = MasterSeed;
            for (int i = 0; i < args.Length; i++)
            {
                if (args[i] == "--out" && i + 1 < args.Length) { outPath = args[++i]; continue; }
                if (args[i] == "--seed" && i + 1 < args.Length)
                {
                    long s;
                    if (!long.TryParse(args[i + 1], NumberStyles.Integer, CultureInfo.InvariantCulture, out s))
                    {
                        Console.Error.WriteLine("--seed wants a whole number");
                        return 2;
                    }
                    seed = s; i++; continue;
                }
                Console.Error.WriteLine("usage: EconSim [--out <file>] [--seed <n>]");
                return 2;
            }

            var md = new Md();
            Header(md, seed);
            Scenarios.One(md, seed);
            Scenarios.Two(md, seed);
            Scenarios.Three(md, seed);
            Scenarios.Four(md, seed);
            Scenarios.Five(md, seed);
            Scenarios.Six(md, seed);
            Checks.Seven(md, seed);
            Checks.Eight(md, seed);
            Scenarios.Nine(md, seed);
            Scenarios.Ten(md, seed);
            Verdict(md, seed);

            string text = md.Render();
            if (outPath != null)
            {
                string dir = Path.GetDirectoryName(Path.GetFullPath(outPath));
                if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
                File.WriteAllText(outPath, text, new UTF8Encoding(false));
                Console.WriteLine("wrote " + outPath + ", " + Sim.N(text.Length) + " characters; checks " +
                                  (Checks.AllPassed ? "PASSED" : "FAILED"));
            }
            else
            {
                Console.Out.Write(text);
            }
            return Checks.AllPassed ? 0 : 1;
        }

        // =====================================================================================

        private static void Header(Md md, long seed)
        {
            md.Line("# Ingvar's economy, played off-game");
            md.Blank();
            md.Line("*Generated by `tests/EconSim` from the shipping `ValkyriesCargo/Core` sources. Do not edit by hand.*");
            md.Blank();
            md.Line("Seed **" + Sim.N(seed) + "**. Regenerate:");
            md.Blank();
            md.Line("```powershell");
            md.Line(".\\tools\\run-econsim.ps1");
            md.Line("# or: dotnet run --project tests\\EconSim\\EconSim.csproj -c Release -- --out docs\\ECONOMY-SIM.md");
            md.Line("```");
            md.Blank();
            md.Line("The economy is blind until players trade (DESIGN section 12), and the first real visit has not happened yet. This");
            md.Line("report is that visit, simulated: `Market.StartVisit`, `Market.Settle` and `Market.Relax` — the same file the server");
            md.Line("runs, compiled into a console harness the way `tests/CoreTests` does it — driven by players with coins, bags and");
            md.Line("appetites. Every number below came out of the code, not out of a model of the code. Nothing here changes a default:");
            md.Line("the last section proposes, the owners decide.");

            var rules = Sim.Shipped;   // what SHIPS, not the core's baseline -- see Sim.Shipped
            Catalogue cat = Sim.DefaultCatalogue();
            md.Blank();
            md.Table(new[] { "the numbers it ran on", "value", "where from" }, new List<string[]>
            {
                new[] { "catalogue", Sim.N(cat.Count) + " entries (" + Sim.N(cat.CountOf(EntryKind.Ware)) + " Wares, " + Sim.N(cat.CountOf(EntryKind.Want)) + " Wants)", "`Catalogue.DefaultLine`, parsed by the shipping parser" },
                new[] { "`PriceElasticity`", Sim.F(rules.Elasticity, 2), "`ModConfig` default" },
                new[] { "`MinPriceMultiplier` / `MaxPriceMultiplier`", Sim.F(rules.MinMultiplier, 1) + " / " + Sim.F(rules.MaxMultiplier, 1), "`ModConfig` defaults" },
                new[] { "`SpreadBuy`", Sim.F(rules.Spread, 1), "`ModConfig` default" },
                new[] { "`FairMarketAct`", rules.FairMarketAct ? "on" : "off", "`ModConfig` default" },
                new[] { "`WareHalfLifeGameDays` / `WantHalfLifeGameDays`", (rules.WareHalfLifeGameDays <= 0 ? "never" : Sim.F(rules.WareHalfLifeGameDays, 1)) + " / " + (rules.WantHalfLifeGameDays <= 0 ? "never" : Sim.F(rules.WantHalfLifeGameDays, 1)), "`ModConfig` defaults (the owner, 2026-09-07: wares never, wants 3; scenario 10)" },
                new[] { "`PurseCoins` / `PurseCarryPercent` / cap", Sim.N(rules.PurseCoins) + " / " + Sim.N(rules.PurseCarryPercent) + "% of the GROSS / " + Sim.N(rules.PurseCapMultiple) + "x", "`ModConfig` defaults" },
                new[] { "a game day", Sim.F(rules.SecondsPerGameDay, 0) + " s", "`EnvMan.m_dayLengthSec`, verified on StormTest 2026-09-06" },
            });
        }

